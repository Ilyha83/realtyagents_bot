async def analyze_market(query: str = None) -> str:
    """
    Анализирует рынок и отвечает на юридические/финансовые вопросы.
    При общем запросе выдает мгновенный актуальный отчёт из БД.
    При специфическом запросе подключает экспертную LLM.
    """
    if not query:
        return build_market_overview_report()

    # Загружаем базу знаний для точечного вопроса клиента
    kb_path = os.path.join(os.path.dirname(__file__), '..', 'data', 'legal_kb.json')
    try:
        with open(kb_path, 'r', encoding='utf-8') as f:
            kb_data = json.load(f)
            kb_text = json.dumps(kb_data, ensure_ascii=False, indent=2)
    except Exception as e:
        kb_text = "База знаний недоступна."

    system_prompt = ANALYST_PROMPT.format(knowledge_base=kb_text)
    user_msg = f"Запрос клиента: {query}\n\nДай краткий, точный ответ по законам/рынку Северного Кипра."

    try:
        response = await ask_llm(
            system_prompt=system_prompt,
            user_message=user_msg,
            temperature=0.3,
            max_tokens=600,
        )
        if "Извините, произошла ошибка" not in response:
            if "дисклеймер" not in response.lower() and "disclaimer" not in response.lower():
                response = response.strip() + LEGAL_DISCLAIMER_MD
            return response
    except Exception:
        pass

    return build_market_overview_report()


